"""Measure music loudness and generate conservative playback gains.
Never re-encode music: only gains change, preserving original stereo files.
Requires FFmpeg. Run from any folder with Python.
"""
from pathlib import Path
import concurrent.futures
import json
import subprocess

ROOT = Path(__file__).resolve().parents[2]
MUSIC = ROOT / "assets/audio/music"
TARGET_LUFS = -20.0
PEAK_CEILING = -3.0


def measure(path):
    result = subprocess.run(["ffmpeg", "-hide_banner", "-nostats", "-i", str(path),
                             "-af", "loudnorm=I=-20:TP=-3:LRA=11:print_format=json",
                             "-f", "null", "-"], capture_output=True, text=True, check=True)
    raw = result.stderr[result.stderr.rfind("{\n"):]
    stats, _ = json.JSONDecoder().raw_decode(raw)
    loudness, peak = float(stats["input_i"]), float(stats["input_tp"])
    gain = min(TARGET_LUFS - loudness, PEAK_CEILING - peak, 0.0)
    key = path.relative_to(MUSIC).as_posix()
    return key, {"input_lufs": loudness, "input_true_peak_db": peak,
                 "playback_gain_db": round(gain, 2),
                 "expected_lufs": round(loudness + gain, 2),
                 "expected_true_peak_db": round(peak + gain, 2)}


def main():
    files = sorted((MUSIC / "v2").glob("*.ogg"))
    files += [MUSIC / f"jingle_finish_{result}.ogg" for result in ("win", "good", "lose")]
    with concurrent.futures.ThreadPoolExecutor(max_workers=3) as pool:
        measurements = dict(pool.map(measure, files))
    code = '# Generated by tools/audio/measure_music.py; gain only, no lossy re-encoding.\n'
    code += 'extends RefCounted\n\nconst GAIN_DB := {\n'
    for name, entry in sorted(measurements.items()):
        code += f'\t"{name}": {entry["playback_gain_db"]},\n'
    code += '}\n'
    (ROOT / "scripts/audio").mkdir(exist_ok=True)
    (ROOT / "scripts/audio/music_levels.gd").write_text(code, encoding="utf-8")
    (ROOT / "docs/music_levels.json").write_text(json.dumps(measurements, indent=2) + "\n", encoding="utf-8")
    for name, entry in measurements.items():
        print(f'{name}: {entry["input_lufs"]} LUFS -> {entry["expected_lufs"]} LUFS, gain {entry["playback_gain_db"]} dB')


if __name__ == "__main__":
    main()
